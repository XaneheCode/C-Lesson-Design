/* ========== main() — 数据生成主函数 ========== */

/**
 * main() — 生成所有数据文件
 *
 * 【生成流程】
 *   1. 创建data目录(如不存在)
 *   2. 生成products.txt: 遍历product_defs,逐行写入
 *   3. 生成sales.txt: 遍历sale_defs,自动补全ID/名称/类别/总额
 *   4. 生成purchases.txt: 遍历purchase_defs,自动补全ID/名称/类别/总额
 *
 * 【数据格式】
 *   products.txt: id|name|category|manufacturer|model|stock|price
 *   sales.txt:    id|product_id|name|category|date|quantity|price|total
 *   purchases.txt: (同sales格式)
 */
int main(void) {
    /* 创建data目录(兼容Windows的mkdir和Linux的mkdir -p) */
    system("mkdir -p data 2>nul || mkdir data 2>nul");

    /* ===== 生成 products.txt ===== */
    FILE *fp = fopen("data/products.txt", "w");
    if (!fp) {
        printf("Error: Cannot create data/products.txt\n");
        return 1;
    }
    /* 写入表头行 */
    fprintf(fp, "id|name|category|manufacturer|model|stock|price\n");
    /* 遍历商品定义,逐行写入 */
    for (int i = 0; i < PRODUCT_COUNT; i++) {
        fprintf(fp, "%s|%s|%s|%s|%s|%d|%.2f\n",
            product_defs[i].id, product_defs[i].name, product_defs[i].category,
            product_defs[i].manufacturer, product_defs[i].model,
            product_defs[i].stock, product_defs[i].price);
    }
    fclose(fp);
    printf("Generated data/products.txt (%d records)\n", PRODUCT_COUNT);

    /* ===== 生成 sales.txt ===== */
    fp = fopen("data/sales.txt", "w");
    if (!fp) {
        printf("Error: Cannot create data/sales.txt\n");
        return 1;
    }
    fprintf(fp, "id|product_id|name|category|date|quantity|price|total\n");
    for (int i = 0; i < SALE_COUNT; i++) {
        /* 自动生成销售编号: S001, S002, ... */
        char sale_id[16];
        sprintf(sale_id, "S%03d", i + 1);

        /* 根据product_id查找对应的商品名称和类别(冗余填充) */
        const char *pname = "";
        const char *pcat = "";
        for (int j = 0; j < PRODUCT_COUNT; j++) {
            if (strcmp(product_defs[j].id, sale_defs[i].product_id) == 0) {
                pname = product_defs[j].name;
                pcat = product_defs[j].category;
                break;
            }
        }

        /* 计算销售总额 = 数量 × 售价 */
        double total = sale_defs[i].quantity * sale_defs[i].unit_price;
        fprintf(fp, "%s|%s|%s|%s|%s|%d|%.2f|%.2f\n",
            sale_id, sale_defs[i].product_id, pname, pcat,
            sale_defs[i].date, sale_defs[i].quantity,
            sale_defs[i].unit_price, total);
    }
    fclose(fp);
    printf("Generated data/sales.txt (%d records)\n", SALE_COUNT);

    /* ===== 生成 purchases.txt ===== */
    fp = fopen("data/purchases.txt", "w");
    if (!fp) {
        printf("Error: Cannot create data/purchases.txt\n");
        return 1;
    }
    fprintf(fp, "id|product_id|name|category|date|quantity|price|total\n");
    for (int i = 0; i < PURCHASE_COUNT; i++) {
        /* 自动生成进货编号: B001, B002, ... */
        char pur_id[16];
        sprintf(pur_id, "B%03d", i + 1);

        /* 根据product_id查找商品名称和类别 */
        const char *pname = "";
        const char *pcat = "";
        for (int j = 0; j < PRODUCT_COUNT; j++) {
            if (strcmp(product_defs[j].id, purchase_defs[i].product_id) == 0) {
                pname = product_defs[j].name;
                pcat = product_defs[j].category;
                break;
            }
        }

        /* 计算进货总额 = 数量 × 进价 */
        double total = purchase_defs[i].quantity * purchase_defs[i].unit_price;
        fprintf(fp, "%s|%s|%s|%s|%s|%d|%.2f|%.2f\n",
            pur_id, purchase_defs[i].product_id, pname, pcat,
            purchase_defs[i].date, purchase_defs[i].quantity,
            purchase_defs[i].unit_price, total);
    }
    fclose(fp);
    printf("Generated data/purchases.txt (%d records)\n", PURCHASE_COUNT);

    printf("\nData generation complete!\n");
    return 0;
}
